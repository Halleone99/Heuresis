-- ---------------------------------------------------------------------------
-- Phase transitions (Learning <-> Review) join the existing append-only card
-- history. The phase is client-written JSON text inside card data, so it is read
-- with a pattern rather than a cast: a malformed value must never abort a card
-- write. Only the added 'learning_phase' block is new; the rest of the function
-- is unchanged from 20261002162736_heuresis_card_state_changes.sql.
-- ---------------------------------------------------------------------------
alter table public.heuresis_card_state_changes
  drop constraint if exists heuresis_card_state_changes_state_kind_check;
alter table public.heuresis_card_state_changes
  add constraint heuresis_card_state_changes_state_kind_check
  check (state_kind in ('retention', 'role', 'sorted', 'learning_phase'));

create or replace function public.heuresis_log_card_state_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old_sorted text;
  v_new_sorted text;
  v_old_phase  text;
  v_new_phase  text;
begin
  v_new_phase := substring(new.data ->> '_acquisition_v1' from '"phase"\s*:\s*"(learning|review)"');

  if tg_op = 'INSERT' then
    -- changed_at records when the database observed the state. Do not borrow
    -- created_at here: imports may preserve an older source creation date.
    insert into public.heuresis_card_state_changes
      (user_id, card_id, pack_id, state_kind, from_state, to_state, changed_at)
    values
      (new.user_id, new.id, new.pack_id, 'retention', null, new.retention, now()),
      (new.user_id, new.id, new.pack_id, 'role', null, new.role, now());

    v_new_sorted := new.data ->> '_sorted_at';
    if v_new_sorted is not null then
      insert into public.heuresis_card_state_changes
        (user_id, card_id, pack_id, state_kind, from_state, to_state, changed_at)
      values
        (new.user_id, new.id, new.pack_id, 'sorted', null, v_new_sorted, now());
    end if;

    if v_new_phase is not null then
      insert into public.heuresis_card_state_changes
        (user_id, card_id, pack_id, state_kind, from_state, to_state, changed_at)
      values
        (new.user_id, new.id, new.pack_id, 'learning_phase', null, v_new_phase, now());
    end if;

    return new;
  end if;

  if new.retention is distinct from old.retention then
    insert into public.heuresis_card_state_changes
      (user_id, card_id, pack_id, state_kind, from_state, to_state)
    values
      (new.user_id, new.id, new.pack_id, 'retention', old.retention, new.retention);
  end if;

  if new.role is distinct from old.role then
    insert into public.heuresis_card_state_changes
      (user_id, card_id, pack_id, state_kind, from_state, to_state)
    values
      (new.user_id, new.id, new.pack_id, 'role', old.role, new.role);
  end if;

  -- Sort completion lives in card data as _sorted_at, written through
  -- heuresis_patch_card_data. Stored as text rather than cast to timestamptz:
  -- the value is client-supplied and a bad cast would abort the card write.
  v_old_sorted := old.data ->> '_sorted_at';
  v_new_sorted := new.data ->> '_sorted_at';
  if v_new_sorted is not null and v_new_sorted is distinct from v_old_sorted then
    insert into public.heuresis_card_state_changes
      (user_id, card_id, pack_id, state_kind, from_state, to_state)
    values
      (new.user_id, new.id, new.pack_id, 'sorted', v_old_sorted, v_new_sorted);
  end if;

  -- New -> Learning, New -> Review, Learning -> Review, Review -> Learning (Relearn).
  v_old_phase := substring(old.data ->> '_acquisition_v1' from '"phase"\s*:\s*"(learning|review)"');
  if v_new_phase is not null and v_new_phase is distinct from v_old_phase then
    insert into public.heuresis_card_state_changes
      (user_id, card_id, pack_id, state_kind, from_state, to_state)
    values
      (new.user_id, new.id, new.pack_id, 'learning_phase', v_old_phase, v_new_phase);
  end if;

  return new;
end
$$;

revoke all on function public.heuresis_log_card_state_change() from public, anon, authenticated;

-- A starting point for cards that already carry a phase. Asserted, not observed
-- (origin = 'backfill'): changed_at is migration time, as for the earlier kinds.
insert into public.heuresis_card_state_changes
  (user_id, card_id, pack_id, state_kind, from_state, to_state, origin, changed_at)
select c.user_id, c.id, c.pack_id, 'learning_phase', null,
       substring(c.data ->> '_acquisition_v1' from '"phase"\s*:\s*"(learning|review)"'),
       'backfill', now()
from public.heuresis_cards c
where substring(c.data ->> '_acquisition_v1' from '"phase"\s*:\s*"(learning|review)"') is not null
  and not exists (
    select 1 from public.heuresis_card_state_changes s
    where s.card_id = c.id and s.state_kind = 'learning_phase'
  );
