-- Heuresis Learn: five-exercise learning rounds.
--
-- NEW -> LEARN -> REVIEW share one card row. A card's phase stays where it already
-- lives (heuresis_cards.data ->> '_acquisition_v1', written through
-- heuresis_patch_card_data), so every existing card, every Review rule and the
-- offline queue keep working unchanged. This migration adds only what Learn was
-- missing:
--
--   heuresis_learn_rounds    one round of exactly five exercises for one card
--   heuresis_learn_attempts  the first answer to each exercise (0 or 10 points)
--
-- Scoring cannot be duplicated: an attempt is identified by (round_id, position),
-- positions are 1..5, points are derived from the answer by the database, and the
-- client can only write through the functions below. A double click, a refresh or
-- a replayed offline request repeats the same key and changes nothing.
--
-- Nothing here touches heuresis_card_events or heuresis_card_stats: a Learning
-- exercise is never a Review grade.
--
-- Safe to run more than once. Existing rows are not rewritten.

create table if not exists public.heuresis_learn_rounds (
  -- Generated by the client so that a retried "start" finds its own round.
  id             uuid primary key,
  user_id        uuid not null references auth.users(id) on delete cascade,
  card_id        uuid not null references public.heuresis_cards(id) on delete cascade,
  pack_id        uuid not null references public.heuresis_packs(id) on delete cascade,
  -- The card's Learning cycle (1 = first acquisition, 2 = first Relearn, ...).
  cycle          integer not null check (cycle >= 0),
  round_number   integer not null check (round_number >= 1),
  -- The five exercises exactly as they were shown, so a refresh resumes the same round.
  plan           jsonb not null check (jsonb_typeof(plan) = 'array' and jsonb_array_length(plan) = 5),
  status         text not null default 'active' check (status in ('active', 'completed', 'abandoned')),
  score          integer not null default 0 check (score between 0 and 50),
  -- Exercises that earned their points: right at the first attempt, without a hint.
  correct_count  integer not null default 0 check (correct_count between 0 and 5),
  recall_correct boolean not null default false,
  -- Ready for Review: at least 40/50 and the final active-recall exercise right, unaided.
  ready          boolean not null default false,
  started_at     timestamptz not null default now(),
  completed_at   timestamptz,
  constraint heuresis_learn_rounds_number_once unique (card_id, cycle, round_number),
  constraint heuresis_learn_rounds_ready_rule
    check (not ready or (status = 'completed' and score >= 40 and recall_correct))
);

comment on table public.heuresis_learn_rounds is
  'One Learning round (five exercises) for one card. Written only by heuresis_learn_* functions.';

-- A card has at most one unfinished round, on any device.
create unique index if not exists heuresis_learn_rounds_one_active
  on public.heuresis_learn_rounds (card_id) where status = 'active';
create index if not exists heuresis_learn_rounds_card_idx
  on public.heuresis_learn_rounds (user_id, card_id, cycle desc, round_number desc);
create index if not exists heuresis_learn_rounds_pack_idx
  on public.heuresis_learn_rounds (pack_id);

create table if not exists public.heuresis_learn_attempts (
  round_id      uuid not null references public.heuresis_learn_rounds(id) on delete cascade,
  position      smallint not null check (position between 1 and 5),
  user_id       uuid not null references auth.users(id) on delete cascade,
  card_id       uuid not null references public.heuresis_cards(id) on delete cascade,
  pack_id       uuid not null references public.heuresis_packs(id) on delete cascade,
  stage         text not null check (stage in ('recognition', 'reconstruction', 'completion', 'context', 'recall')),
  exercise_type text not null check (char_length(exercise_type) between 1 and 40),
  -- The first answer only. Correcting it afterwards never changes these columns.
  correct       boolean not null,
  assisted      boolean not null default false,
  points        smallint not null,
  response      text not null default '' check (char_length(response) <= 1000),
  expected      text not null default '' check (char_length(expected) <= 1000),
  -- Set when the learner practised the right answer after feedback (no points).
  corrected_at  timestamptz,
  created_at    timestamptz not null default now(),
  primary key (round_id, position),
  constraint heuresis_learn_attempts_points_rule
    check (points = case when correct and not assisted then 10 else 0 end)
);

comment on table public.heuresis_learn_attempts is
  'First answer to each exercise of a Learning round. One row per (round, position): points cannot be earned twice.';

create index if not exists heuresis_learn_attempts_user_time_idx
  on public.heuresis_learn_attempts (user_id, created_at desc);
create index if not exists heuresis_learn_attempts_card_idx
  on public.heuresis_learn_attempts (card_id);
create index if not exists heuresis_learn_attempts_pack_idx
  on public.heuresis_learn_attempts (pack_id);

alter table public.heuresis_learn_rounds enable row level security;
alter table public.heuresis_learn_attempts enable row level security;

-- Read-only to the client; the functions below are the only writers.
revoke all on table public.heuresis_learn_rounds from public, anon, authenticated;
revoke all on table public.heuresis_learn_attempts from public, anon, authenticated;
grant select on table public.heuresis_learn_rounds to authenticated;
grant select on table public.heuresis_learn_attempts to authenticated;

