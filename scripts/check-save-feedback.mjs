import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const doc = readFileSync("src/components/workspace/DocumentPage.tsx","utf8");
const capture = readFileSync("src/components/workspace/QuickCapture.tsx","utf8");
const css = readFileSync("src/components/workspace/workspace.css","utf8");
assert.match(doc,/kind: "idle" \| "dirty" \| "saving" \| "local" \| "saved"/);
assert.match(doc,/const needsSync = !sync\.online \|\| sync\.pending > 0;/);
assert.match(doc,/kind: stillDirty \? "dirty" : needsSync \? "local" : "saved"/);
assert.match(doc,/On device · waiting to sync/);
assert.match(doc,/subscribeOfflineSync\(\(state\) =>/);
assert.match(doc,/!state\.pending && !state\.syncing && !state\.error/);
assert.match(doc,/current\.kind === "local"/);
assert.match(doc,/kind: "saved", at: new Date\(\)\.toISOString\(\), message: "Synced"/);
assert.match(doc,/save\.kind === "local" \? save\.message/);
assert.match(doc,/save\.kind === "error" \? <button type="button" onClick=\{\(\) => void persist\(\)\}/);
assert.match(capture,/saving \? <><span className="ws-spinner is-small" aria-hidden="true" \/> Saving…/);
assert.doesNotMatch(css,/\.nb-save-state \{ display: none; \}/);
assert.match(css,/\.nb-save-state\.is-local \{ color: var\(--ws-warn\); \}/);
assert.match(css,/\.nb-doc-actions \{ flex: 1 1 100%; width: 100%; justify-content: space-between;/);
console.log("Document Save/Sync status and Quick Capture feedback checks passed.");
