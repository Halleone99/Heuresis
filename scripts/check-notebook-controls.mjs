import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const notebook = readFileSync("src/components/workspace/NotebookView.tsx", "utf8");
const shell = readFileSync("src/App.tsx", "utf8");
const context = readFileSync("src/components/workspace/WorkspaceContext.tsx", "utf8");
const cards = readFileSync("src/components/workspace/SubjectCard.tsx", "utf8");
const quick = readFileSync("src/components/workspace/QuickCapture.tsx", "utf8");
const detached = readFileSync("src/components/workspace/DetachedNoteWorkspace.tsx", "utf8");
const documentPage = readFileSync("src/components/workspace/DocumentPage.tsx", "utf8");
const windowCss = readFileSync("src/components/workspace/note-window.css", "utf8");
const css = readFileSync("src/components/workspace/workspace.css", "utf8");

assert.match(notebook, /buttonLabel="New"/, "Single New action");
for (const name of ["New subject", "New topic", "New note"]) assert.ok(notebook.includes(name), name);
assert.doesNotMatch(notebook, /New lesson|Recent lessons|Recently edited notes/);
assert.match(notebook, /<SubjectCard key=\{subject.id\}/);
assert.match(cards, /onDoubleClick=/, "Double-click opens subject editing");
assert.match(cards, /workspace.renameSubjectById/);
assert.match(cards, /indexedDB.open/);
assert.match(cards, /type="file"/);
assert.match(cards, /nb-colour-option/);
assert.match(quick, /workspace.addSubject\("Unsorted"\)/, "Uncategorised capture supported");
assert.match(css, /\.nb-cover-backdrop/);
assert.match(css, /\.nb-main-tools \.nb-new-button/);
assert.match(notebook, /const showKind = topic.name.trim\(\).toLocaleLowerCase\(\) !== kindLabel.toLocaleLowerCase\(\)/);
assert.match(notebook, /!topic \? \(/, "Subject pages only display topic cards");
assert.match(notebook, /entry.topic_id === topic.id && isDocument\(entry\)/, "Topic notes are not flattened from other topics");
assert.match(notebook, /className="nb-topic-grid"/, "Subjects show topic cards");
assert.match(notebook, /<div className="nb-scope-actions">[\s\S]*?nb-capture-open[\s\S]*?\{newAction\}/, "Home actions include Captures and New");
assert.match(notebook, /<CaptureReviewPage/);
assert.match(notebook, /nb-capture-summary/);
const review = readFileSync("src/components/workspace/CaptureReviewPage.tsx", "utf8");
assert.match(review, /workspace\.openCleanup\(\{ kind: "inbox", id: inbox.id \}\)/);
assert.match(review, /onOpenNote\(entry\)/);
assert.doesNotMatch(notebook, /mistakes.length \? <p className="nb-scope-meta"/, "No distracting mistake shortcut under subject headings");
assert.match(notebook, /<small>\{metadata \|\| "Note"\}<\/small>/, "Note list keeps a readable type label");
assert.match(context, /if \(next === "notebook"\)/, "Explicit Notebook section navigation targets its home");
assert.match(context, /docId: null, topicId: null, subjectId: null/, "Notebook home clears the retained note and topic");
assert.match(context, /if \(!options.stayInSection\) onSection\("notebook"\)/, "Direct document openings still bypass home reset");
assert.match(context, /onSection\("notebook"\);\s*\}, \[onSection\]\);/, "Direct topic openings still bypass home reset");
assert.match(shell, /onClick=\{\(\) => navigateSection\(id\)\}/, "Sidebar and mobile section buttons share section navigation");
assert.match(shell, /run: \(\) => navigateSection\(item.id\)/, "Command palette uses section navigation");
assert.match(shell, /navigateSection\(SECTIONS\[Number\(event.code.slice\(5\)\) - 1\].id\)/, "Alt shortcuts use section navigation");
assert.match(shell, /startupNotebook\.current = false;\s*workspace.goTo\("notebook"\);/, "Restored Notebook section starts at home");
assert.ok(!detached.includes("startInEditMode detached"), "Existing detached notes should open in reader mode");
assert.ok(documentPage.includes("Boolean(newDoc) || startInEditMode"), "Brand-new notes remain editable");
assert.ok(documentPage.includes('title="Edit (E)"'), "Reading mode must have an Edit button");
assert.ok(documentPage.includes('workspace.writable && !detached ? <button type="button" className="nb-continue"'),
  "Detached readers should not show a second inline Edit button");
assert.ok(windowCss.includes(".nb-detached-root .nb-doc:not(.is-editing) .nb-doc-body"), "Reader uses a document sheet");
console.log("Notebook capture, home navigation, subject customisation and detached-reader checks passed.");