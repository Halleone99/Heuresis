// Generates src/lib/catalogue/pdf/fontManifest.generated.ts from the installed
// @fontsource packages. The manifest is the single list of font files used by
// Catalogue pages: the same WOFF files are registered for the screen (FontFace)
// and embedded in exported PDFs, so on-screen layout and PDF glyphs agree.
//
//   node scripts/generate-catalogue-fonts.mjs
//
// WOFF (not WOFF2) is used on purpose: the PDF embedder converts WOFF to SFNT
// with the platform's own zlib decompressor. @pdf-lib/fontkit's WOFF2 decoder
// fails to subset several of these fonts (verified 29 Oct 2026).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const OUT = resolve(root, "src/lib/catalogue/pdf/fontManifest.generated.ts");

// [package, css file, family name used by Catalogue pages, registered for screen by Catalogue?]
// Families already loaded globally by src/main.tsx are embedded in PDFs only.
const FACES = [
  ["eb-garamond", "400.css", "EB Garamond", true],
  ["eb-garamond", "400-italic.css", "EB Garamond", true],
  ["eb-garamond", "600.css", "EB Garamond", true],
  ["eb-garamond", "600-italic.css", "EB Garamond", true],
  ["cormorant-garamond", "500.css", "Cormorant Garamond", true],
  ["cormorant-garamond", "500-italic.css", "Cormorant Garamond", true],
  ["cormorant-garamond", "600.css", "Cormorant Garamond", true],
  ["libre-caslon-display", "400.css", "Libre Caslon Display", false],
  ["noto-serif", "400.css", "Noto Serif", false],
  ["noto-serif", "400-italic.css", "Noto Serif", false],
  ["noto-serif", "700.css", "Noto Serif", false],
  ["inter", "400.css", "Inter", false],
  ["inter", "500.css", "Inter", false],
  ["inter", "600.css", "Inter", false],
  // Chinese: a private family name so the rest of Heuresis keeps its current
  // system CJK fonts. Regular weight only; bold/italic are synthesised alike
  // on screen and in the PDF.
  ["noto-serif-sc", "400.css", "Heuresis Catalogue SC", true],
];

const imports = [];
const entries = [];
let n = 0;
for (const [pkg, css, family, screen] of FACES) {
  const path = resolve(root, "node_modules/@fontsource", pkg, css);
  if (!existsSync(path)) throw new Error(`Missing ${path}. Run npm install first.`);
  const text = readFileSync(path, "utf8");
  for (const block of text.split("@font-face").slice(1)) {
    const style = /font-style:\s*(normal|italic)/.exec(block)?.[1];
    const weight = Number(/font-weight:\s*(\d+)/.exec(block)?.[1]);
    const woff = /url\(\.\/files\/([^)]+\.woff)\)\s*format\('woff'\)/.exec(block)?.[1];
    const ranges = /unicode-range:\s*([^;]+);/.exec(block)?.[1]?.trim() ?? "U+0-10FFFF";
    if (!style || !weight || !woff) throw new Error(`Unexpected @font-face in ${pkg}/${css}`);
    // A single combined CJK file duplicates the numbered subsets; skip it.
    if (/chinese-simplified/.test(woff)) continue;
    const id = `f${n++}`;
    imports.push(`import ${id} from "@fontsource/${pkg}/files/${woff}?url";`);
    entries.push(`  { family: ${JSON.stringify(family)}, weight: ${weight}, style: ${JSON.stringify(style)}, screen: ${screen}, ranges: ${JSON.stringify(ranges)}, url: ${id} },`);
  }
}

const source = `// GENERATED by scripts/generate-catalogue-fonts.mjs — do not edit by hand.
// ${entries.length} WOFF subset files from @fontsource packages (SIL Open Font Licence).
${imports.join("\n")}

export type CatalogueFontFile = {
  family: string;
  weight: number;
  style: "normal" | "italic";
  /** Registered for on-screen Catalogue pages by Catalogue itself (others are loaded globally). */
  screen: boolean;
  /** CSS unicode-range of this subset file. */
  ranges: string;
  url: string;
};

export const CATALOGUE_FONT_FILES: CatalogueFontFile[] = [
${entries.join("\n")}
];
`;
writeFileSync(OUT, source);
console.log(`Wrote ${entries.length} font files to ${OUT}`);
