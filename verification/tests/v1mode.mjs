// Before the v2 migration is applied: existing v1 notes stay readable, writes are blocked clearly, Study works.
import { check, launch, section, shot, signIn, sql } from "./lib.mjs";
const { browser, page, errors } = await launch();
await signIn(page);
await section(page, "Notebook");
await page.waitForSelector(".ws-schema-notice");
check((await page.locator(".ws-schema-notice").innerText()).includes("20261012090000_knowledge_workspace_v2.sql"), "read-only notice names the migration");
await page.click(".nb-tree-row.is-subject .nb-tree-twisty").catch(() => undefined);
await page.click("text=Inbox");
await page.waitForSelector(".nb-doc-row");
check(await page.locator(".nb-doc-row").count() === 2, "existing v1 notes listed");
await page.click(".nb-doc-row:has-text('Lesson · 11 Oct 2026')");
await page.waitForSelector(".nb-doc-title");
check((await page.locator(".nb-doc-eyebrow").innerText()).toUpperCase().includes("LESSON"), "legacy 'Lesson ·' note is presented as a lesson");
check(await page.locator(".nb-doc-actions button:has-text('Edit')").count() === 0, "no Edit button while read-only");
await shot(page, "v1-readonly");
await page.keyboard.press("Control+Shift+KeyN");
await page.waitForSelector(".qc-panel");
await page.keyboard.type("should not save");
await page.keyboard.press("Control+Enter");
await page.waitForSelector(".qc-panel .ws-field-error");
check((await page.locator(".qc-panel .ws-field-error").innerText()).includes("database update"), "capture explains why it cannot save; text stays in the panel");
check(await sql("select count(*) from knowledge_records where body = 'should not save'") === "0", "nothing written");
await page.keyboard.press("Escape");
await section(page, "Mistake Log");
check((await page.locator(".ml-card").count()) === 1, "v1 mistake visible");
await section(page, "Study");
await page.waitForTimeout(800);
check((await page.locator(".desktop-content").innerText()).includes("Chinese"), "Study unaffected");
check(errors.length === 0, `no page errors (${errors.length})`);
await browser.close();
